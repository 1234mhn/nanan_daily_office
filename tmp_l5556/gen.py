def build_line(n, st, en, kr, cn, d):
    words, phrase, pattern, ex1, ex2, phon = d
    wgrid = ''.join(f'<div><b>{html.escape(w)}</b> — {html.escape(m)}</div>' for w, m in words)
    kr_esc = html.escape(kr)
    return (
f'''<div class="line" data-time-start="{st}" data-time-end="{en}">  <div class="line-hd" onclick="toggleExp(this)">    <span class="arr">▸</span>    <p class="kr" style="flex:1">{n}. {kr_esc}</p>    <button class="speak" onclick="event.stopPropagation();handleSpeak(event,'{kr_esc}')">🔊</button>  </div>  <p class="cn">→ {html.escape(cn)}</p>  <div class="line-exp" style="display:none">    <div class="item"><b>📍单词</b><div style="display:grid;grid-template-columns:1fr 1fr;gap:2px 16px;margin-top:4px">{wgrid}</div></div>    <div class="item"><b>💬 短语</b><br><span class="m">{html.escape(phrase)}</span></div>    <div class="item"><b>📌句型</b><br><span class="m">{pattern}</span></div>    <div class="ex">💬例句1 <span class="c">{ex1}</span></div>    <div class="ex">💬例句2 <span class="c">{ex2}</span></div>    <div class="phon"><b>🎵 音变</b><br><span class="m">{html.escape(phon)}</span></div>  </div></div>''')

def vocab_grid(lx, wx):
    """从6件套单词去重生成单词汇总网格"""
    seen = {}
    for n, st, en, kr, cn in lx:
        for w, m in wx[n][0]:
            if w not in seen and not w.startswith('-') and not w.startswith('('):
                seen[w] = m
    return ''.join(f'<div style="font-size:13px;padding:3px 0"><b>{html.escape(w)}</b> — {html.escape(m)}</div>' for w, m in seen.items())

def build_page(num, title, video, lines, dx):
    s = SKEL
    # 标题
    s = s.replace('<title>第61课 · 失恋喝酒</title>', f'<title>第{num}课 · {title}</title>')
    s = s.replace('<h2>第61课 · 失恋喝酒</h2>', f'<h2>第{num}课 · {title}</h2>')
    s = s.replace('onclick="toggleQuiz(61)"', f'onclick="toggleQuiz({num})"')
    # 视频
    s = re.sub(r'<video controls preload="auto" src="[^"]*"></video>',
               f'<video controls preload="auto" src="{video}"></video>', s)
    # 台词块：替换 <div class="content"> 之后到 <div class="sec">💡 小贴士 之前
    start = s.index('<div class="content">')
    head_end = s.index('<div class="sec">📝 台词（点击展开讲解）</div>') + len('<div class="sec">📝 台词（点击展开讲解）</div>')
    # find tail markers
    tip_idx = s.find('<div class="sec">💡 小贴士</div>')
    if tip_idx == -1:
        # fallback: find done-toggle
        tip_idx = s.find('<button class="done-toggle"')
    # 老台词块区间 = head_end .. tip_idx
    newblocks = '\n'.join(build_line(n, st, en, kr, cn, dx[n]) for n, st, en, kr, cn in lines)

    # 单词汇总/语法总结：找 lesson61 的对应区块，替换 inner
    # lesson61 可能没有 单词汇总/语法总结 → 我们插入在 tip 之前
    vocab_html = f'''<div class="sec" onclick="toggleVocab(this)" style="cursor:pointer;user-select:none">📌 单词汇总（点击展开）</div>
<div id="vocab{num}" style="display:none"><div style="background:#fff;border:1px solid #eee;border-radius:10px;padding:12px;display:grid;grid-template-columns:1fr 1fr;gap:2px 16px">{vocab_grid(lines, dx)}</div></div>
'''
    s = s[:head_end] + '\n' + newblocks + '\n' + vocab_html + s[tip_idx:]
    # data-lesson / toggleDone / startPractice / data-note / noteStatus
    s = s.replace('data-lesson="61"', f'data-lesson="{num}"').replace('toggleDone(61)', f'toggleDone({num})')
    s = s.replace('startPractice(61)', f'startPractice({num})')
    s = s.replace('data-note="61"', f'data-note="{num}"')
    s = s.replace('noteStatus61', f'noteStatus{num}')
    return s

