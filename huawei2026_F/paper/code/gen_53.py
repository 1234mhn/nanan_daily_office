"""5.3 问题三章节（算力约束下的多维资源联合优化与结构性转移）"""

def build_53(doc, L):
    H1,H2,H3,BODY,CAP,TABLE,P,PAGEBREAK,FIGURE = (L[k] for k in
        ['H1','H2','H3','BODY','CAP','TABLE','P','PAGEBREAK','FIGURE'])
    FIG_DIR = L['FIG_DIR']

    H2(doc, "5.3 问题三模型建立与求解")

    # ============ 5.3.1 ============
    H3(doc, "5.3.1 问题三求解思路")
    BODY(doc, "问题三的核心任务是在算力预算有限时，求解参数量 N_B、数据量 D_B 与数据质量 Q 之间的最优配置，"
              "并分析当预算水平变化时最优分配是否发生本质改变。"
              "长上下文又会额外引入与 N_B、D_B 和 L_ctx 共同增长的注意力计算，"
              "使仅按 6ND 配置训练资源失去准确性。")
    BODY(doc, "本文的技术路线为：在问题二乘性质量缩放律基础上，把训练计算、质量提升和长上下文注意力统一折算为 FLOPs；"
              "在给定预算 C 与外生上下文长度 L_ctx 下联合优化 N_B、D_B 和 Q。"
              "模型先由 KKT 条件刻画边际资源配置关系，再用 SLSQP 多初值求解、"
              "确定性网格独立验证，并在连续预算扫描上采用 PELT 与活跃集变化共同识别结构转变。")
    BODY(doc, "本问的输入由问题二主模型参数、问题一 Q_0 与 p_star、C7 的 L_ctx 以及题设成本参数组成。"
              "最终采用问题二经 BIC 和留出误差共同选出的乘性质量缩放律作为目标函数，"
              "第三问只改变资源约束，不重新拟合损失函数，从而保持跨问题参数口径一致。")

    # ============ 5.3.2 ============
    H3(doc, "5.3.2 问题三模型建立")
    BODY(doc, "（1）决策变量与成本构成")
    BODY(doc, "决策变量为 N_B、D_B 和 Q；领域配比 p 固定为问题一参考配比附近的局部最优 p_star；"
              "L_ctx 作为外生场景量，不参与优化。基础训练成本、质量提升成本与注意力成本分别为：")
    P(doc, "C_train = 6×10^18 · N_B · D_B", size=12, align=1, sa=3)
    P(doc, "C_quality = 10^9 · D_B · [g(Q) − g(Q_0)]_+", size=12, align=1, sa=3)
    P(doc, "C_attn = η_attn × 10^18 · N_B · D_B · L_ctx", size=12, align=1, sa=3)
    BODY(doc, "其中 η_attn=2×10^−4，Q_0 由问题一真实结果计算为 0.605095。"
              "总成本满足 C_train + C_quality + C_attn ≤ C。"
              "预算取 10^19、10^22 和 10^24 FLOPs，并用 61 个对数等距预算点检查连续变化。"
              "C7 共 45 条有效记录，L_ctx 的观测范围为 2048 至 131072，"
              "五个实际场景为 2048、4096、8192、32768 和 131072。")
    BODY(doc, "（2）质量成本函数选取")
    BODY(doc, "质量成本分别采用指数型、幂函数型和对数渐进型三种形式：")
    P(doc, "指数型：g(Q) = a·[exp(b(Q − Q_0)) − 1]", size=12, align=1, sa=3)
    P(doc, "幂函数型：g(Q) = a·(Q − Q_0)^b", size=12, align=1, sa=3)
    P(doc, "对数渐进型：g(Q) = a·ln(1 + b(Q − Q_0))", size=12, align=1, sa=3)
    BODY(doc, "三种形式分别求解，不将其参数混合估计。该处理把成本机制不确定性转化为模型情景比较，"
              "避免用缺少观测依据的权重合成三种函数。N_B、D_B 的优化范围沿用问题二数据支撑范围："
              "0.070542 ≤ N_B ≤ 10000、0.1 ≤ D_B ≤ 36000；Q_0 ≤ Q ≤ 1。")
    BODY(doc, "（3）优化模型与 KKT 条件")
    BODY(doc, "在固定 p_star 下，第二问乘性质量模型可写为 L = L_p·[1 + κ(1−Q)^μ]。"
              "完整优化模型为：")
    P(doc, "min L(N_B, D_B, Q)　s.t.　C_train + C_quality + C_attn ≤ C", size=11, align=1, sa=3)
    BODY(doc, "预算紧约束允许消去 D_B，用于独立网格验证。注意力成本与基础训练成本之比为：")
    P(doc, "C_attn / C_train = (η_attn · L_ctx) / 6", size=12, align=1, sa=3)
    BODY(doc, "该比值不依赖 N_B、D_B 和预算。令 x=(N_B, D_B, Q)，C_total=C_train+C_quality+C_attn，"
              "以 u_(j,−) 和 u_(j,+) 表示变量下、上界乘子，拉格朗日函数为：")
    P(doc, "𝓛 = L(x) + λ(C_total − C) − Σ_j u_(j,−)(x_j − x_j^min) + Σ_j u_(j,+)(x_j − x_j^max)",
      size=10.5, align=1, sa=3)
    BODY(doc, "当 N_B、D_B 和 Q 均为内部解时，KKT 驻点条件可写成相同的单位算力边际损失下降：")
    P(doc, "M_N = M_D = M_Q = λ", size=12, align=1, sa=3)
    BODY(doc, "若 Q=1，则互补松弛给出 M_Q ≥ λ；若 Q=Q_0，则 M_Q ≤ λ。"
              "由 C_attn/C_train 的常数比可得使注意力开销与训练开销相当的临界上下文长度：")
    P(doc, "L_ctx_crit = 6 / η_attn = 30000", size=12, align=1, sa=3)
    BODY(doc, "（4）结构转变的识别方法")
    BODY(doc, "定义连续预算扫描的标度指数 ξ(C) = d ln(N_B·D_B) / d ln C。"
              "将三类成本份额、Q 和 ξ(C) 标准化为序列 z_i，PELT 求解：")
    P(doc, "min Σ_i [ Σ_(t∈段) ‖z_t − z̄_段‖² + β·|段数| ]", size=11, align=1, sa=3)
    BODY(doc, "结构转变表现为成本份额、最优质量或标度指数的统计分段变化，并结合质量变量活跃集核验。"
              "该处理把结构变化转化为 PELT 可识别的多变量变点，避免人为设置份额跳变阈值。")

    # ============ 5.3.3 ============
    H3(doc, "5.3.3 问题三模型求解与分析")
    BODY(doc, "（1）临界上下文与求解精度")
    BODY(doc, "C7 的 45 条记录均通过有效性检查。上下文长度最小为 2048、最大为 131072；"
              "理论临界值 L_ctx_crit=30000 位于实际观测的 8192 与 32768 之间，"
              "因此临界区间可由真实 C7 场景覆盖。")
    FIGURE(doc, FIG_DIR + "/q3_fig1.png")
    CAP(doc, "图5.13　C7 上下文长度对最优配置与成本比例的影响")
    BODY(doc, "45 个主场景中 SLSQP 成功收敛 45 个，最大预算相对残差为 3.188e−12。"
              "KKT 诊断中，45 个场景的 N_B 与 D_B 单位算力边际收益最大相对差为 5.687e−07，"
              "Q 边界或内部条件满足 45/45。独立网格验证的最大相对损失差为 2.531e−13，"
              "N_B、D_B 最大相对差分别为 9.724e−07 和 9.196e−07，最大 Q 绝对差为 5.174e−08。"
              "两种数值路径在全部主场景中一致。")
    BODY(doc, "（2）最优资源路径")
    BODY(doc, "在 L_ctx=32768 下，三类成本函数均表现为预算增加时 N_B 和 D_B 持续扩大、损失持续下降。"
              "指数型成本在 10^19 FLOPs 时给出 Q=0.948353 的内部解；"
              "幂函数型和对数渐进型在该预算下已取 Q=1。"
              "到 10^22 与 10^24 FLOPs 时，三类成本函数均达到 Q=1，"
              "最优损失差异分别小于 0.0022 和 0.00014。")
    FIGURE(doc, FIG_DIR + "/q3_fig2.png")
    CAP(doc, "图5.14　L_ctx 为 32768 时最优 N_B、D_B 与 Q 的预算路径")
    BODY(doc, "指数型成本下，10^19 FLOPs 的基础训练、质量提升和注意力份额依次为 "
              "0.3369、0.2952 和 0.3680；到 10^22 FLOPs 时变为 0.4606、0.0363 和 0.5031；"
              "到 10^24 FLOPs 时质量份额降至 0.0049。"
              "质量达到上界后，新增预算主要分配给 N_B·D_B 乘积。")
    FIGURE(doc, FIG_DIR + "/q3_fig3.png")
    CAP(doc, "图5.15　指数型质量成本的三类算力份额")
    BODY(doc, "（3）结构转变识别")
    BODY(doc, "指数型成本的首个变点位于 1.212×10^19 与 1.468×10^19 FLOPs 之间，"
              "几何中心为 1.334×10^19 FLOPs；PELT 与 Q 由内部解转为饱和解的活跃集变化在同一位置。"
              "指数型后续 PELT 变点约为 1.101×10^20 和 1.616×10^21 FLOPs，"
              "幂函数型约为 9.085×10^19 和 1.616×10^21 FLOPs，"
              "对数渐进型约为 5.109×10^19 和 6.190×10^20 FLOPs。"
              "这些后续变点表示成本份额和标度指数的分段变化，不等同于 Q 边界切换。")
    FIGURE(doc, FIG_DIR + "/q3_fig4.png")
    CAP(doc, "图5.16　PELT 与活跃集识别的预算结构转变")
    BODY(doc, "（4）成本函数形式的影响")
    BODY(doc, "三类 g(Q) 的低预算差异明显：在 10^19 FLOPs、L_ctx=32768 时，"
              "对数渐进型的最优损失为 2.869331，指数型为 2.940650，幂函数型为 2.956751。"
              "该排序来自题设成本参数及函数形状，表示在相同预算下质量提升的价格不同；"
              "它不代表某一种成本函数已被数据验证为真实机制。")
    FIGURE(doc, FIG_DIR + "/q3_fig5.png")
    CAP(doc, "图5.17　质量成本形式对成本份额的影响")
    BODY(doc, "（5）结构转变的数学定义与结果边界")
    BODY(doc, "本文将结构转变定义为：在预算连续变化时，最优解从“质量变量处于内部解”"
              "转为“质量变量触及上界”的活跃集切换，并伴随成本份额与标度指数的统计分段变化。"
              "对指数型成本，该转变发生在约 1.334×10^19 FLOPs 处，"
              "即预算较低时优先提升数据质量，预算跨越该数量级后转向扩大参数与数据规模。")
    BODY(doc, "本问结论需说明以下边界：① 数值结论仅覆盖题设三个预算数量级、"
              "61 点预算扫描区间以及 C7 真实上下文长度，不外推到更小或更大的 L_ctx；"
              "② 质量成本参数由题设给定而非附件拟合，因此三种函数应作为并列情景报告，"
              "正文不据此宣称某一种机制真实成立；"
              "③ N_B、D_B 的规模上界来自问题二数据支撑范围，"
              "当最优解触及边界时应解释为当前经验模型的适用边界，而不是物理上限。")
