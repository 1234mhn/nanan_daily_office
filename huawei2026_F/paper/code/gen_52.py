    BODY(doc, "（4）弹性、替代与边际收益")
    BODY(doc, "主模型选择 L_2。在 p=p_ref 处令 F(Q)=1+κ(1−Q)^μ，则各维度的偏导数为：")
    P(doc, "∂L_2/∂N = −F·α·A_N·N^(−α−1)", size=12, align=1, sa=3)
    P(doc, "∂L_2/∂D = −F·β·A_D·D^(−β−1)", size=12, align=1, sa=3)
    P(doc, "∂L_2/∂Q = −L_0 · κμ(1 − Q)^(μ−1)", size=12, align=1, sa=3)
    BODY(doc, "定义弹性 ε_X = (X/L_2)·(∂L_2/∂X)，X∈{N, D, Q}。按 C=0.006·N·D 计算训练量，"
              "若扩展路径保持 D/N 不变，则 N 和 D 均与 C 的平方根成正比。"
              "单位算力边际损失下降（MRC）与质量—参数替代率分别为：")
    P(doc, "MRC = −∂L_2/∂C = −[N(∂L_2/∂N) + D(∂L_2/∂D)] / (2C)", size=12, align=1, sa=3)
