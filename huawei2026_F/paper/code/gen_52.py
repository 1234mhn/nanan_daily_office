    BODY(doc, "该处理把较低的配比损失映射为较大的有效数据量，同时限制跨尺度解释范围。")
    BODY(doc, "（3）两种候选的质量扩展形式")
    BODY(doc, "候选形式一（有效数据量式）把质量和配比共同映射为有效数据量，并保留低质量惩罚：")
    P(doc, "D_eff = D · Q^(θ_Q) · m(p)", size=12, align=1, sa=3)
    P(doc, "L_1 = E + A_N·N^(−α) + A_D·D_eff^(−β) + G[Q^(−γ) − 1]", size=11, align=1, sa=3)
    BODY(doc, "候选形式二（乘性质量式）先用 m(p) 修正数据量，再让质量作用于完整经典损失：")
    P(doc, "L_p = E + A_N·N^(−α) + A_D·[D·m(p)]^(−β)", size=11, align=1, sa=3)
    P(doc, "L_2 = L_p · [1 + κ(1 − Q)^μ]", size=12, align=1, sa=3)
    BODY(doc, "两种形式在 Q=1、p=p_ref 时均自动退化为经典标度律。对每种候选模型计算残差平方和 SSE，"
              "并以参数个数 k 惩罚复杂度：")
