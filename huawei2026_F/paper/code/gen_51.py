    H1(doc, "五、模型建立与求解")
    H2(doc, "5.1 问题一模型建立与求解")
    H3(doc, "5.1.1 问题一求解思路")
    BODY(doc, "问题一的核心任务是建立多源语料的质量评价体系，识别并消解指标间的评价冲突，"
              "并进一步建立领域配比与验证损失之间的定量关系。本文的技术路线为："
              "先对 22 个质量指标做方向统一与归一化，再以语义分组抑制同类评分器的重复计权，"
              "构建分组熵权综合评价模型得到域级质量评分；"
              "随后以百分位秩定义冲突强度，采用加权中位数做稳健聚合；"
              "最后在单纯形约束下建立配比与损失的线性模型与二阶组合模型，并做独立检验与跨尺度诊断。"
              "整体求解思路如图 5.1 所示。")
