    BODY(doc, "分别对 13 个验证域的交叉熵损失拟合模型，并以 13 域 Loss 的等权均值作为综合指标。"
              "线性主模型形如：")
    P(doc, "L_(i,m) = a_m + Σ_(l=1)^17 β_(l,m)·p_(i,l) + ε_(i,m),　Σ_(l=1)^17 β_(l,m) = 0",
      size=12, align=1, sa=3)
    BODY(doc, "主模型仅用 A4/A5 的 512 组 1M 配方估计。由于各配比之和为 1，加入截距后系数存在平移不唯一性，"
              "以系数和为 0 固定表示。在保留线性解释模型的基础上，进一步引入 136 个 p_i·p_j 二阶项，"
              "采用岭回归抑制过拟合：")
    P(doc, "L_mean = a_quad + Σ_(l=1)^17 β_quad_l·p_l + Σ_(i<j) γ_(i,j)·p_i·p_j + ε",
      size=12, align=1, sa=3)
    BODY(doc, "对特征按训练折均值和标准差标准化；截距不惩罚，最小化残差平方和加 λ 倍系数平方和。"
              "λ 候选为 0.01、0.1、1、10、100、1000，只在 512 组训练配方内进行相同划分的 5 折验证，"
              "检验集不参与选 λ。")

