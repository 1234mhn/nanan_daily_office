    BODY(doc, "（1）指标预处理与方向统一")
    BODY(doc, "各指标的含义以原数据集字段说明核验。fineweb_edu 提取单值；"
              "ad_en 取“无广告”减“有广告”的 logit 差，fluency_en 取“流畅”减“不流畅”的 logit 差，两者均为正向。"
              "四个 modernbert 字段为 0—5 级分类输出，以 softmax 期望等级保留连续信息：")
    P(doc, "X_(s,j) = Σ_(k=0)^5 k·exp(z_(s,j,k)) / Σ_(k=0)^5 exp(z_(s,j,k))",
      size=12, align=1, sa=3)
    BODY(doc, "实际计算先减去最大 logit 以避免溢出。qurater 四维分别描述文风、知识门槛、事实知识与教育价值，"
              "采用四项原始评分的等权均值，属于建模选择而非原题指定权重。"
              "计数指标取 ln(1+x)，三个 DSIR 字段在本数据中全部非正，取 ln(1−x) 后反向归一化，"
              "以保留“原始 DSIR 越大越优”的相对方向。将正向指标缩放为 V=(X−min)/(max−min)，反向指标取 1−V；"
              "常量列设为 0.5 并将熵权置零。全部 22 个指标的处理规则如表 2 所示。")
    BODY(doc, "（2）分组熵权综合评价模型")
    BODY(doc, "为减少同类评分器数量不同造成的重复计权，将 22 个指标归为六组。各组先取中位数，"
              "再依据组间信息差异计算熵权。记组内中位数为 G_(s,g)，则：")
    P(doc, "P_(s,g) = G_(s,g) / Σ_(s=1)^n G_(s,g)", size=12, align=1, sa=3)
    P(doc, "E_g = − Σ_(s=1)^n P_(s,g)·ln P_(s,g) / ln n", size=12, align=1, sa=3)
    P(doc, "w_g = (1 − E_g) / Σ_(h=1)^6 (1 − E_h)", size=12, align=1, sa=3)
    P(doc, "S_s = Σ_(g=1)^6 w_g · G_(s,g)", size=12, align=1, sa=3)
    BODY(doc, "约定 0·ln0=0。熵权反映当前附件中组评分的离散程度，并非因果重要性。"
              "域级质量评分 S_d 取该域全部记录的 S_s 算术均值，不额外假设各域 Token 规模。")
    BODY(doc, "（3）冲突识别与稳健聚合")
    BODY(doc, "对各指标 V 采用平均并列秩，同值对应同秩。令 rank_avg 为 1 起算的并列平均名次，"
              "以 R=(rank_avg−0.5)/n 形成百分位秩。冲突强度定义为同一样本在不同指标上的最大秩差：")
    P(doc, "c_s = max_j R_(s,j) − min_j R_(s,j)", size=12, align=1, sa=3)
    P(doc, "δ = quantile(c, 0.90);　conflict_s = 1{c_s ≥ δ}", size=12, align=1, sa=3)
    BODY(doc, "稳健消解在同一秩尺度进行。把组权重均分至组内指标，令 w_j=w_g/|group g|，"
              "定义秩加权均值 S_rank 作为对照，并取加权中位数 S_star。"
              "加权中位数是加权绝对偏差之和的最小化解，可降低极端指标的影响：")
